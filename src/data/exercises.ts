/** Convenience lookup by id. */
export const EXERCISE_BY_ID: Record<string, Exercise> = EXERCISE_LIBRARY.reduce(
  (acc, exercise) => {
    acc[exercise.id] = exercise;
    return acc;
  },
  {} as Record<string, Exercise>,
);

export function findExercise(exerciseId: string, library: Exercise[] = EXERCISE_LIBRARY): Exercise | null {
  return library.find((exercise) => exercise.id === exerciseId) ?? null;
}
